"""Install the locked Linux toolchain and execute an optional command in it."""
from __future__ import annotations

import hashlib
import os
from pathlib import Path
import platform
import shlex
import shutil
import subprocess
import sys
import tarfile
import tempfile
import tomllib
import urllib.request
import zipfile

ROOT = Path(__file__).resolve().parents[1]
TOOLS = ROOT / '.tools'


def digest(path: Path) -> str:
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def install(name: str, spec: dict) -> Path:
    cache = TOOLS / 'downloads'
    cache.mkdir(parents=True, exist_ok=True)
    archive = cache / spec['archive']
    if not archive.exists():
        print(f"Downloading {name} {spec['version']}", flush=True)
        partial = archive.with_suffix(archive.suffix + '.partial')
        try:
            with urllib.request.urlopen(spec['url'], timeout=60) as src, partial.open('wb') as dst:
                shutil.copyfileobj(src, dst)
            if digest(partial) != spec['sha256']:
                raise RuntimeError(f'{name}: downloaded SHA256 mismatch')
            partial.replace(archive)
        finally:
            partial.unlink(missing_ok=True)
    if digest(archive) != spec['sha256']:
        raise RuntimeError(f'{archive}: SHA256 mismatch; remove the corrupt archive explicitly')
    target = TOOLS / name
    # Always extract the verified archive, including on subsequent runs.
    with tempfile.TemporaryDirectory(dir=TOOLS) as temporary:
        stage = Path(temporary)
        if spec['format'] == 'zip':
            with zipfile.ZipFile(archive) as package:
                for member in package.infolist():
                    dest = (stage / member.filename).resolve()
                    if not dest.is_relative_to(stage.resolve()):
                        raise RuntimeError(f'Unsafe archive member: {member.filename}')
                    package.extract(member, stage)
                    mode = member.external_attr >> 16
                    if mode and not member.is_dir():
                        dest.chmod(mode & 0o777)
        elif spec['format'] == 'tar.gz':
            with tarfile.open(archive) as package:
                package.extractall(stage, filter='data')
        else:
            raise ValueError(f"Unsupported archive format: {spec['format']}")
        extracted = stage / spec['root']
        for relative in spec['executables']:
            path = extracted / relative
            if not path.is_file():
                raise FileNotFoundError(path)
            path.chmod(path.stat().st_mode | 0o111)
        if target.exists():
            shutil.rmtree(target)
        extracted.rename(target)
    print(f"Installed {name} {spec['version']}", flush=True)
    return target


def main() -> None:
    config = tomllib.loads((ROOT / 'ci/external-tools.toml').read_text())
    if (platform.system(), platform.machine()) != ('Linux', 'x86_64'):
        raise RuntimeError('This lock supports Linux x86_64 only')
    locations = {name: install(name, spec) for name, spec in config['tools'].items()}
    radioss = locations['openradioss']
    paths = [locations['uv'], radioss / 'exec', locations['paraview'] / 'bin']
    libraries = [radioss / 'extlib/hm_reader/linux64', radioss / 'extlib/h3d/lib/linux64']
    values = {
        'OPENRADIOSS_PATH': str(radioss),
        'RAD_CFG_PATH': str(radioss / 'hm_cfg_files'),
        'RAD_H3D_PATH': str(libraries[1]),
        'OMP_STACKSIZE': '400m',
        'OMP_NUM_THREADS': '2',
    }
    env = dict(os.environ, **values)
    env['PATH'] = ':'.join(map(str, paths)) + ':' + os.environ['PATH']
    env['LD_LIBRARY_PATH'] = ':'.join(map(str, libraries)) + (':' + os.environ['LD_LIBRARY_PATH'] if os.environ.get('LD_LIBRARY_PATH') else '')
    env['PYTHONDONTWRITEBYTECODE'] = '1'
    activation = ['# Generated by ci/bootstrap.py; do not edit.']
    activation += [f'export {key}={shlex.quote(value)}' for key, value in values.items()]
    activation += [f'export PATH={shlex.quote(":".join(map(str, paths)))}:"$PATH"',
                   f'export LD_LIBRARY_PATH={shlex.quote(":".join(map(str, libraries)))}${{LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}}']
    (TOOLS / 'env.sh').write_text('\n'.join(activation) + '\n')
    for name, spec in config['tools'].items():
        for executable in spec['executables']:
            binary = locations[name] / executable
            if name != 'uv':
                result = subprocess.run(['ldd', str(binary)], env=env, text=True, capture_output=True, check=True)
                if 'not found' in result.stdout:
                    raise RuntimeError(f'Missing system libraries for {binary}:\n{result.stdout}')
        if 'check' in spec:
            subprocess.run([str(locations[name] / spec['check'][0]), *spec['check'][1:]], env=env, check=True, timeout=60)
    subprocess.run(['uv', 'sync', '--locked'], cwd=ROOT, env=env, check=True)
    subprocess.run(['uv', 'run', '--locked', 'python', '-c',
                    'import mujoco; m=mujoco.MjModel.from_xml_string("<mujoco><worldbody/></mujoco>"); mujoco.mj_step(m,mujoco.MjData(m))'],
                   cwd=ROOT, env=env, check=True)
    if sys.argv[1:]:
        subprocess.run(sys.argv[1:], cwd=ROOT, env=env, check=True)
    print('Bootstrap complete. Activate tools: source .tools/env.sh', flush=True)


if __name__ == '__main__':
    try:
        main()
    except Exception as error:
        print(f'FATAL: {error}', file=sys.stderr)
        raise
